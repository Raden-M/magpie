// Regenerate THIRD-PARTY.md from the dependency graphs themselves.
//
// The backend links its Rust dependencies into a single binary and the
// extension bundles two libraries into `content.js`, so both are redistributed
// and both carry attribution duties. Deriving the list from `cargo` and
// `node_modules` keeps it from drifting the moment a dependency changes.
//
// Run with `make licenses`.

import { execFile } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(root, "backend");
const extension = resolve(root, "extension");

/**
 * The crates actually compiled into the binary.
 *
 * `cargo metadata` alone would also list dev- and build-dependencies, which are
 * never distributed - `cargo tree -e normal` is what the binary really carries.
 */
async function rustCrates() {
  const { stdout: treeOut } = await run(
    "cargo",
    ["tree", "-e", "normal", "--prefix", "none", "--no-dedupe"],
    { cwd: backend, maxBuffer: 32 * 1024 * 1024 },
  );
  const linked = new Set();
  for (const line of treeOut.split("\n")) {
    const match = line.trim().match(/^([a-zA-Z0-9_.-]+) v(\d[^ ]*)/);
    if (match && match[1] !== "magpie") linked.add(`${match[1]} ${match[2]}`);
  }

  const { stdout: metaOut } = await run(
    "cargo",
    ["metadata", "--format-version", "1"],
    { cwd: backend, maxBuffer: 64 * 1024 * 1024 },
  );
  const meta = JSON.parse(metaOut);

  return meta.packages
    .filter((p) => linked.has(`${p.name} ${p.version}`))
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? "(see repository)",
      repository: p.repository ?? "",
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** The libraries esbuild bundles into the extension. */
async function npmPackages() {
  const pkg = JSON.parse(await readFile(resolve(extension, "package.json"), "utf8"));
  const out = [];
  for (const name of Object.keys(pkg.dependencies ?? {})) {
    const dir = resolve(extension, "node_modules", name);
    const meta = JSON.parse(await readFile(resolve(dir, "package.json"), "utf8"));
    const files = (await readdir(dir)).filter((f) => /^licen[cs]e/i.test(f)).sort();
    out.push({
      name,
      version: meta.version,
      license: meta.license ?? "(see repository)",
      repository: meta.homepage ?? "",
      files,
    });
  }
  return out;
}

function licenceTable(rows) {
  const lines = ["| Package | Version | License |", "| --- | --- | --- |"];
  for (const r of rows) {
    const name = r.repository ? `[${r.name}](${r.repository})` : r.name;
    lines.push(`| ${name} | ${r.version} | ${r.license} |`);
  }
  return lines.join("\n");
}

function summarise(rows) {
  const counts = new Map();
  for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([licence, n]) => `- \`${licence}\` - ${n}`)
    .join("\n");
}

const crates = await rustCrates();
const npm = await npmPackages();

const body = `<!-- Generated by scripts/generate-third-party.mjs - run \`make licenses\`. Do not edit. -->

# Third-party licenses

Magpie is [MIT licensed](LICENSE). It redistributes the work below, which stays under
the licenses named here.

Both halves of Magpie ship other people's code inside a single artifact: the backend
statically links its Rust dependencies into one binary, and the extension bundles
Readability and DOMPurify into \`content.js\`. The extension carries the full license
texts alongside it as \`THIRD-PARTY.txt\`, written at build time.

## Extension (bundled into \`content.js\`)

${licenceTable(npm)}

Full texts ship in \`THIRD-PARTY.txt\` in every extension build.

## Backend (linked into the \`magpie\` binary)

${summarise(crates)}

Every crate below is permissively licensed; none imposes a copyleft obligation on
Magpie itself. The \`MPL-2.0\` crates are used unmodified, so their file-level source
requirement is met by their own upstream repositories.

<details>
<summary>All ${crates.length} crates</summary>

${licenceTable(crates)}

</details>
`;

await writeFile(resolve(root, "THIRD-PARTY.md"), body);
console.log(`THIRD-PARTY.md: ${crates.length} crates, ${npm.length} npm packages`);
